export function defenceText(checked: Record<string, boolean>) {
  const lines = ["چک لیست آمادگی دفاع — تزنویسه / قلم", "این فهرست عمومی است. آیین نامه دانشگاه شما ممکن است موارد اضافه بخواهد.", ""];
  for (const section of DEFENCE_SECTIONS) {
    lines.push(`## ${section.title}`);
    section.items.forEach((item, i) => {
      const key = `${section.id}-${i}`;
      lines.push(`${checked[key] ? "[x]" : "[ ]"} ${item}`);
    });
    lines.push("");
  }
  return lines.join("\n");
}
